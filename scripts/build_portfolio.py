def build(data: dict) -> dict[str, str]:
    validate(data)
    graph = data['structured_data']
    detailed = [p for p in data['projects'] if p.get('facets')]
    pages = {'index.html': home(data, graph), 'work/index.html': work(data, graph), 'about/index.html': about(data, graph), 'library/index.html': library(data, graph)}
    pages['classic/index.html'] = build_classic.render(data, json.loads((ROOT / 'blog/search.json').read_text()), ROOT)
    for project in detailed:
        pages[f'work/{project["slug"]}/index.html'] = case(project, detailed, graph, data)
    return pages


def validate(data: dict) -> None:
    """Catch content mistakes before creating files or constructing URLs."""
    if not isinstance(data, dict):
        raise ValueError('portfolio.json must contain an object')
    projects = data.get('projects')
    if not isinstance(projects, list) or not projects:
        raise ValueError('projects must be a nonempty list')
    seen = set()
    for project in projects:
        if not isinstance(project, dict):
            raise ValueError('each project must be an object')
        slug = project.get('slug', '')
        if not isinstance(slug, str) or not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', slug):
            raise ValueError(f'Project slug must be URL-safe: {slug!r}')
        if slug in seen:
            raise ValueError(f'Duplicate project slug: {slug}')
        seen.add(slug)
        if project.get('category') not in CATEGORIES:
            raise ValueError(f'{slug}: unknown project category')
        for field in ('title', 'summary', 'status'):
            if not isinstance(project.get(field), str) or not project[field].strip():
                raise ValueError(f'{slug}: missing {field}')
        if not isinstance(project.get('tags'), list) or not all(isinstance(tag, str) for tag in project['tags']):
            raise ValueError(f'{slug}: tags must be a list of strings')
        if project.get('facets') and set(project['facets']) != {'Problem', 'Built', 'Tradeoff', 'Evidence'}:
            raise ValueError(f'{slug}: a case study needs Problem, Built, Tradeoff and Evidence')
    for slug in FEATURED:
        if slug not in seen:
            raise ValueError(f'Featured project {slug!r} is missing; update FEATURED in the generator')


def sync(pages: dict[str, str], *, check: bool = False) -> list[str]:
    """Write current pages and prune only obsolete pages this generator owns."""
    root = ROOT.resolve()
    for rel in pages:
        if not (root / rel).resolve().is_relative_to(root):
            raise ValueError(f'Output path leaves the repository: {rel}')
    changed = []
    for rel, content in pages.items():
        path = root / rel
        if not path.exists() or path.read_text(encoding='utf-8') != content:
            changed.append(rel)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content, encoding='utf-8')
    for path in sorted((root / 'work').rglob('index.html')):
        rel = path.relative_to(root).as_posix()
        if rel in pages or path.is_symlink() or not path.resolve().is_relative_to(root):
            continue
        if GENERATED_MARKER in path.read_text(encoding='utf-8')[:256]:
            changed.append(f'(obsolete) {rel}')
            if not check:
                path.unlink()
    return changed


def main() -> int:
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument('--check', action='store_true')
    options = args.parse_args()
    try:
        pages = build(json.loads(SOURCE.read_text(encoding='utf-8')))
        changed = sync(pages, check=options.check)
    except (OSError, ValueError, KeyError) as exc:
        print(f'Portfolio content/build error: {exc}', file=sys.stderr)
        return 1
    if options.check and changed:
        print('Portfolio output is stale: ' + ', '.join(changed))
        return 1
    print(f'Portfolio: {len(pages)} pages, {len(changed)} changed.' if not options.check else f'Portfolio output up to date ({len(pages)} pages).')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
