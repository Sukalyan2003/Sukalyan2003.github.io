def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def relative(fragment: str, prefix: str) -> str:
    """Rebase the retained public HTML without changing external destinations."""
    return re.sub(r'(href|src)="(?!https?:|mailto:|#|data:)([^"]+)"',
                  lambda m: f'{m[1]}="{prefix}{m[2]}"', fragment)


